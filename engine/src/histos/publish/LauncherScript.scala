package histos.publish

import histos.jdk.{Sha256, Toolchain}
import histos.workspace.{IoFailure, IoFault}

import java.nio.file.{Files, Path}

import zio.{IO, ZIO}

/** `histos` in a checkout. It refuses a JDK older than [[Toolchain.Floor]], installs `shim-<sha256>` when the user shim
  * is missing, and execs that shim. The shim chooses the toolchain and sets `HISTOS_VERSION`.
  */
object LauncherScript:
  def check(repo: Path, sha: Sha256): IO[ScriptError, Unit] =
    agree(repo.resolve("histos"), posix(sha))

  def update(repo: Path, sha: Sha256): IO[ScriptError, Unit] =
    write(repo.resolve("histos"), posix(sha), executable = true)

  def posix(sha: Sha256): String =
    Posix.replace("__SHIM_SHA__", sha.value).replace("__FLOOR__", Toolchain.Floor.value)

  private def agree(path: Path, body: String): IO[ScriptError, Unit] =
    ZIO
      .attemptBlocking {
        if !Files.isRegularFile(path) then Left(ScriptError.Missing(path))
        else if Files.readString(path) == body then Right(())
        else Left(ScriptError.Drift(path))
      }
      .mapError(_ => ScriptError.Io(IoFailure(path, IoFault.Read)))
      .flatMap(ZIO.fromEither)

  private def write(
      path: Path,
      body: String,
      executable: Boolean,
  ): IO[ScriptError, Unit] =
    ZIO
      .attemptBlocking {
        val same = Files.isRegularFile(path) && Files.readString(path) == body
        if !same then Files.writeString(path, body)
        if executable then path.toFile.setExecutable(true)
      }
      .mapError(_ => ScriptError.Io(IoFailure(path, IoFault.Write)))

  private val Posix: String = """#!/bin/sh
# Generated by histos. `histos workflow --update` rewrites this file.
# A missing shim is installed from the content-addressed dist asset, then exec'd.
set -eu
shim_sha=__SHIM_SHA__
fail() { echo "histos: $*" >&2; exit 1; }
hash_of() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | awk '{print $1}'
  else shasum -a 256 "$1" | awk '{print $1}'; fi
}
java_guide='A JDK __FLOOR__ or newer is required. Histos does not install it.
macOS: brew install --cask temurin@__FLOOR__
Linux: https://adoptium.net/temurin/releases?version=__FLOOR__'
os=$(uname -s 2>/dev/null || true)
case $os in
  MINGW*|MSYS*|CYGWIN*|Windows*)
    fail "Histos runs on macOS and Linux. On Windows, use WSL. A native Windows build may come later."
    ;;
esac
java_bin=$(command -v java) || fail "java is not on PATH
$java_guide"
java_text=$("$java_bin" -version 2>&1 || true)
if ! java_found=$(printf '%s\n' "$java_text" | awk '
  /version "/ {
    if (match($0, /"[^"]+"/)) {
      print substr($0, RSTART + 1, RLENGTH - 2)
      found = 1
      exit
    }
  }
  END { if (!found) exit 1 }
'); then
  fail "java version is unreadable
$java_guide"
fi
java_major=$(printf '%s\n' "$java_found" | awk -F. '{ if ($1 == "1" && NF >= 2) print $2 + 0; else print $1 + 0 }')
[ "$java_major" -ge __FLOOR__ ] || fail "java $java_found is older than __FLOOR__
$java_guide"
home=${HISTOS_HOME:-$HOME/.histos}
shim=$home/bin/histos
if [ ! -x "$shim" ]; then
  dist=${HISTOS_DIST:-https://github.com/early-effect/histos/releases/download/dist}
  case $dist in
    https://*) ;;
    http://127.0.0.1|http://127.0.0.1/*|http://127.0.0.1:*|http://localhost|http://localhost/*|http://localhost:*) ;;
    *) fail "dist base is not a supported url: $dist" ;;
  esac
  mkdir -p "$home/bin"
  tmp=$(mktemp)
  curl -fsSL "$dist/shim-$shim_sha" -o "$tmp" || { rm -f "$tmp"; fail "could not fetch shim-$shim_sha"; }
  got=$(hash_of "$tmp")
  if [ "$got" != "$shim_sha" ]; then
    rm -f "$tmp"
    fail "checksum mismatch for shim-$shim_sha"
  fi
  mv "$tmp" "$shim"
  chmod +x "$shim"
fi
exec "$shim" "$@"
"""
end LauncherScript
