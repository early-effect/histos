package histos.workflow

import histos.doctor.DoctorPlacement
import histos.supply.{DailyAudit, MainAlert, PrAuthor, SecurityFixes, Snapshot}
import histos.ProjectGraph

/** Supply-chain workflows. Neither placement adds a job. */
object SupplyYaml:
  val depsName: String  = "histos-deps.yml"
  val auditName: String = "histos-audit.yml"

  def preflight(graph: ProjectGraph, job: String): List[String] =
    graph.supply.placement match
      case DoctorPlacement.WorkflowJobOnly          => Nil
      case DoctorPlacement.PreflightPlusWorkflowJob =>
        List(s"      - run: ./histos doctor --preflight $job")

  def files(graph: ProjectGraph): List[RenderedWorkflow] =
    RenderedWorkflow(depsName, deps(graph)) :: audit(graph).toList

  def supplyChain(graph: ProjectGraph): String =
    val policy = graph.supply
    val name   = policy.checkName.value
    val issues =
      policy.advisories.onMain match
        case MainAlert.Issue(_)  => List("      issues: write")
        case MainAlert.CheckOnly => Nil
    (List(
      s"  $name:"
    ) ++ Workflow.toolchainNeeds(graph) ++ List(
      s"    runs-on: ${Workflow.runner}",
      "    permissions:",
    ) ++ Workflow.actionsRead(graph) ++ List(
      "      contents: read"
    ) ++ issues ++ List(
      "    steps:",
    ) ++ Workflow.fullGitCheckout() ++ List(
      s"      - uses: ${ActionPins.originHead}",
      s"      - uses: ${ActionPins.localSetup}",
      s"      - uses: ${ActionPins.cache.line}",
      "        with:",
      "          path: ~/.cache/histos/advisories",
      "          key: histos-osv-${{ hashFiles('dependencies.lock') }}-${{ github.run_id }}",
      "          restore-keys: histos-osv-",
    ) ++ Workflow.branchJar(graph) ++ preflight(graph, name) ++ List(
      "      - run: ./histos doctor",
      "      - run: ./histos workflow --check",
      "      - run: ./histos resolve --check",
      "      - run: ./histos deps audit",
      "      - if: failure() && github.event_name != 'pull_request'",
      "        run: ./histos deps alert",
      "        env:",
      "          GH_TOKEN: ${{ github.token }}",
    )).mkString("\n")

  def snapshot(graph: ProjectGraph): Option[String] =
    graph.supply.snapshot match
      case Snapshot.Off                  => None
      case Snapshot.OnPushToDefault(job) =>
        val name = job.value
        Some(
          (List(
            s"  $name:"
          ) ++ Workflow.toolchainNeeds(graph) ++ List(
            s"    if: ${quote(Workflow.onDefaultPush)}",
            s"    runs-on: ${Workflow.runner}",
            "    permissions:",
          ) ++ Workflow.actionsRead(graph) ++ List(
            "      contents: write",
            "    steps:",
            s"      - uses: ${ActionPins.checkout.line}",
            s"      - uses: ${ActionPins.localSetup}",
          ) ++ Workflow.fetchAssembly(graph) ++ preflight(graph, name) ++ List(
            "      - run: ./histos deps snapshot --submit"
          )).mkString("\n")
        )

  private def deps(graph: ProjectGraph): String =
    val policy  = graph.supply.updates
    val author  = secrets(policy.author)
    val present = List(
      s"          HISTOS_SECRET_PRESENT_${author.id}: $${{ secrets.${author.id} != '' }}",
      s"          HISTOS_SECRET_PRESENT_${author.key}: $${{ secrets.${author.key} != '' }}",
      "          HISTOS_STEP_APP: ${{ steps.app.outcome }}",
      "          GH_TOKEN: ${{ steps.app.outputs.token }}",
    )
    val opened =
      graph.supply.placement match
        case DoctorPlacement.WorkflowJobOnly          => Nil
        case DoctorPlacement.PreflightPlusWorkflowJob =>
          List(
            "      - run: ./histos doctor --preflight histos-deps",
            "        env:",
          ) ++ present
    (List(
      "# Generated by histos. Do not edit. Run './histos workflow --update' to regenerate.",
      "name: histos-deps",
      "on:",
      "  schedule:",
      s"    - cron: ${quote(policy.schedule.cron.value)}",
      s"      timezone: ${quote(policy.schedule.zone.value)}",
      "  workflow_dispatch:",
      "    inputs:",
      "      dry-run:",
      "        description: doctor plus update, no branch or pull request",
      "        required: false",
      "        type: boolean",
      "        default: false",
      "permissions:",
      "  contents: read",
      "concurrency:",
      "  group: histos-deps",
      "  cancel-in-progress: false",
      "jobs:",
      "  deps:",
      s"    runs-on: ${Workflow.runner}",
      "    steps:",
      "      - id: app",
      "        continue-on-error: true",
      s"        uses: ${ActionPins.appToken.line}",
      "        with:",
      s"          app-id: $${{ secrets.${author.id} }}",
      s"          private-key: $${{ secrets.${author.key} }}",
      "          permission-contents: write",
      "          permission-pull-requests: write",
      "          permission-workflows: write",
    ) ++ Workflow.fullGitCheckout(persistCredentials = false) ++ List(
      s"      - uses: ${ActionPins.originHead}",
      s"      - uses: ${ActionPins.localSetup}",
    ) ++ Workflow.buildAssembly(graph) ++ opened ++ List(
      "      - run: ./histos deps update --yes",
      "      - run: ./histos resolve --update",
      "      - run: ./histos workflow --update",
      "      - run: ./histos deps audit --report",
      "      - if: inputs.dry-run != true",
      "        run: ./histos deps pr",
      "        env:",
      "          GH_TOKEN: ${{ steps.app.outputs.token }}",
      "          HISTOS_DRY_RUN: ${{ inputs.dry-run }}",
    )).mkString("\n") + "\n"

  private def audit(graph: ProjectGraph): Option[RenderedWorkflow] =
    graph.supply.advisories.daily match
      case DailyAudit.Off    => None
      case DailyAudit.On(at) =>
        val security = graph.supply.security match
          case SecurityFixes.OutOfBand(_, _, _) => securityJob(graph)
          case _                                => Nil
        val body = List(
          "# Generated by histos. Do not edit. Run './histos workflow --update' to regenerate.",
          "name: histos-audit",
          "on:",
          "  schedule:",
          s"    - cron: ${quote(at.cron.value)}",
          s"      timezone: ${quote(at.zone.value)}",
          "  workflow_dispatch:",
          "permissions:",
          "  contents: read",
          "  issues: write",
          "jobs:",
          "  audit:",
          s"    runs-on: ${Workflow.runner}",
          "    outputs:",
          "      fixable: ${{ steps.audit.outputs.fixable }}",
          "    steps:",
          s"      - uses: ${ActionPins.checkout.line}",
          s"      - uses: ${ActionPins.localSetup}",
        ) ++ Workflow.buildAssembly(graph) ++ preflight(graph, "audit") ++ List(
          "      - id: audit",
          "        run: ./histos deps audit",
        ) ++ security
        Some(RenderedWorkflow(auditName, body.mkString("\n") + "\n"))

  private def securityJob(graph: ProjectGraph): List[String] =
    val author = secrets(graph.supply.updates.author)
    List(
      "  security:",
      "    needs: audit",
      "    if: needs.audit.outputs.fixable == 'true'",
      s"    runs-on: ${Workflow.runner}",
      "    steps:",
      "      - id: app",
      "        continue-on-error: true",
      s"        uses: ${ActionPins.appToken.line}",
      "        with:",
      s"          app-id: $${{ secrets.${author.id} }}",
      s"          private-key: $${{ secrets.${author.key} }}",
      "          permission-contents: write",
      "          permission-pull-requests: write",
      "          permission-workflows: write",
      s"      - uses: ${ActionPins.checkout.line}",
      "        with:",
      "          persist-credentials: false",
      s"      - uses: ${ActionPins.localSetup}",
    ) ++ Workflow.buildAssembly(graph) ++ preflight(graph, "security") ++ List(
      "      - run: ./histos deps update --security --yes",
      "      - run: ./histos deps pr --security",
      "        env:",
      "          GH_TOKEN: ${{ steps.app.outputs.token }}",
    )

  private final case class AppSecrets(id: String, key: String)

  private def secrets(author: PrAuthor): AppSecrets =
    author match
      case PrAuthor.App(id, key)        => AppSecrets(id.value, key.value)
      case PrAuthor.OwnerOpens(id, key) => AppSecrets(id.value, key.value)
      case PrAuthor.Pat(token)          => AppSecrets(token.value, token.value)

  private def quote(text: String): String =
    "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
end SupplyYaml
