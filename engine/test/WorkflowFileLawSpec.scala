package histos

import histos.workflow.*
import histos.workspace.{IoFailure, IoFault, Workspace}

import java.nio.file.attribute.PosixFilePermissions
import java.nio.file.{Files, Path}

import _root_.scala.jdk.CollectionConverters.*

import zio.{Exit, Scope, ZIO}
import zio.test.*

object WorkflowFileLawSpec extends ZIOSpecDefault:
  private val scala3 = scala"3.10.0"

  given CiBranch = CiBranch("main")

  private val graph    = Projects(module("core", Jvm)(scala3))
  private val finished = Sona.described(ReleaseMode.Automatic)
  private val held     = Sona.described(ReleaseMode.Hold)
  private val root     = Path.of("/repo")

  private val testStep =
    """      - run: "./histos test --affected '${{ needs.affected.outputs.modules }}'""""

  private val banner =
    "# Generated by histos. Do not edit. Run './histos workflow --update' to regenerate.\n"

  private val pinReport =
    "workflow: .github/workflows/custom.yml:1\n" +
      "  actions/checkout@v4 is not pinned: need owner/repo@<40-hex> # <tag>\n" +
      "1 pin fault. Fix with './histos workflow --update' or add the action to SupplyChain.extraActions."

  private type Fault = BuildError | CiError | IoFailure

  def spec = suite("workflow file laws")(
    test("a minimal graph renders ci.yml and histos-deps.yml, and a deployment follow up adds nothing"):
      for
        built <- load
        text  <- body(built)
        open  <- filesOf(built, finished)
        later <- filesOf(built, held)
      yield open match
        case ci :: deps :: Nil =>
          assertTrue(
            ci.name == "ci.yml",
            deps.name == "histos-deps.yml",
            ci.body == text,
            later == open,
            text.startsWith("name: ci\n"),
            text.contains("      - \"main\"\n"),
            text.contains(testStep),
            text.contains("    timeout-minutes: 30\n"),
            deps.body.startsWith(banner),
            deps.body.contains("name: histos-deps\n"),
            deps.body.contains("    - cron: \"0 6 * * 1\"\n"),
            deps.body.contains("      timezone: \"America/Chicago\"\n"),
            Workflow.fileName == "ci.yml",
            Workflow.path(root) == root.resolve(".github").resolve("workflows").resolve("ci.yml"),
            Workflow.file(root, "histos-deps.yml") == root
              .resolve(".github")
              .resolve("workflows")
              .resolve(
                "histos-deps.yml"
              ),
          )
        case other =>
          assertTrue(other.map(_.name) == List("ci.yml", "histos-deps.yml"), later.map(_.name) == other.map(_.name))
    ,
    test("a named difference is that workflow path and the first different line"):
      val same  = "name: histos-deps\n"
      val want  = "on:\n  workflow_dispatch:\n"
      val have  = "on:\n  push:\n"
      val short = "name: ci\n"
      val long  = "name: ci\nextra\n"
      assertTrue(
        Workflow.differsNamed("histos-deps.yml", same, same) == Right(()),
        Workflow.differsNamed("histos-deps.yml", same, "name: other\n") ==
          Left(CiError.Drift(".github/workflows/histos-deps.yml", "line 1\n- name: other\n+ name: histos-deps")),
        Workflow.differsNamed(Workflow.releaseName, want, have) ==
          Left(CiError.Drift(".github/workflows/histos-release.yml", "line 2\n-   push:\n+   workflow_dispatch:")),
        Workflow.differs(short, long) ==
          Left(CiError.Drift(".github/workflows/ci.yml", "line 2\n- extra\n+ ")),
        Workflow.differs(short, long) == Workflow.differsNamed(Workflow.fileName, short, long),
      )
    ,
    test("ci.yml is present only when it is a regular file"):
      ZIO.scoped:
        for
          repo    <- work("histos-wf-present")
          absent  <- present(repo).exit
          _       <- makeDir(Workflow.path(repo))
          folder  <- present(repo).exit
          _       <- remove(Workflow.path(repo))
          _       <- write(Workflow.path(repo), "name: ci\n")
          written <- present(repo)
        yield assertTrue(
          failureOf(absent).contains(CiError.Missing(Workflow.path(repo))),
          failureOf(folder).contains(CiError.Missing(Workflow.path(repo))),
          written == (),
        )
    ,
    test("a missing ci.yml is missing, a missing deps file drifts, and check leaves the drifted line"):
      ZIO.scoped:
        for
          built   <- load
          repo    <- work("histos-wf-drift")
          files   <- filesOf(built, finished)
          empty   <- check(repo, built).exit
          ciBody  <- renderedBody(files, "ci.yml")
          _       <- write(Workflow.path(repo), ciBody)
          sibling <- check(repo, built).exit
          drifted = retitle(ciBody)
          _ <- write(Workflow.path(repo), drifted)
          _ <- ZIO.foreachDiscard(files.filter(_.name != "ci.yml")): item =>
            write(Workflow.file(repo, item.name), item.body)
          changed <- check(repo, built).exit
          kept    <- read(Workflow.path(repo))
          _       <- update(repo, built)
          fixed   <- read(Workflow.path(repo))
        yield assertTrue(
          failureOf(empty).contains(CiError.Missing(Workflow.path(repo))),
          failureOf(sibling).contains(CiError.Drift(".github/workflows/histos-deps.yml", "the file is missing")),
          failureOf(changed).contains(CiError.Drift(".github/workflows/ci.yml", "line 1\n- name: CI\n+ name: ci")),
          kept == drifted,
          drifted.startsWith("name: CI\n"),
          fixed == ciBody,
        )
    ,
    test("update writes the rendered files and deletes only a stale histos workflow"):
      ZIO.scoped:
        for
          built <- load
          repo  <- work("histos-wf-update")
          files <- filesOf(built, finished)
          workflows = repo.resolve(".github").resolve("workflows")
          stale     = workflows.resolve("histos-stale.yml")
          yaml      = workflows.resolve("histos-old.yaml")
          custom    = workflows.resolve("custom.yml")
          gone      = workflows.resolve("histos-gone.yml")
          _         <- write(stale, "uses: actions/checkout@v4\n")
          _         <- write(yaml, "stay\n")
          _         <- write(custom, "name: custom\n")
          _         <- makeDir(gone)
          missing   <- check(repo, built).exit
          updated   <- update(repo, built)
          names     <- entries(workflows)
          bodies    <- ZIO.foreach(files)(item => read(Workflow.file(repo, item.name)))
          keptYaml  <- read(yaml)
          keptOther <- read(custom)
          checked   <- check(repo, built)
          again     <- update(repo, built)
          reread    <- ZIO.foreach(files)(item => read(Workflow.file(repo, item.name)))
        yield assertTrue(
          failureOf(missing).contains(CiError.Missing(Workflow.path(repo))),
          updated == Workflow.path(repo),
          checked == updated,
          again == updated,
          bodies == files.map(_.body),
          reread == bodies,
          keptYaml == "stay\n",
          keptOther == "name: custom\n",
          names.contains("ci.yml"),
          names.contains("histos-deps.yml"),
          names.contains("histos-old.yaml"),
          names.contains("custom.yml"),
          !names.contains("histos-stale.yml"),
          !names.contains("histos-gone.yml"),
          !names.exists(_.endsWith(".tmp")),
        )
    ,
    test("a stale histos workflow drifts even when its action is unpinned, and check does not delete it"):
      ZIO.scoped:
        for
          built <- load
          repo  <- work("histos-wf-orphan")
          files <- filesOf(built, finished)
          _     <- commit(repo, files)
          stale = Workflow.file(repo, "histos-stale.yml")
          _       <- write(stale, "uses: actions/checkout@v4\n")
          drifted <- check(repo, built).exit
          kept    <- read(stale)
          removed <- update(repo, built)
          gone    <- readMaybe(stale)
          clean   <- check(repo, built)
        yield assertTrue(
          failureOf(drifted).contains(
            CiError.Drift(".github/workflows/histos-stale.yml", "this file is not rendered by the graph")
          ),
          kept == "uses: actions/checkout@v4\n",
          removed == Workflow.path(repo),
          gone == None,
          clean == removed,
        )
    ,
    test("an unpinned action in another workflow is a pin fault, and update leaves that file"):
      ZIO.scoped:
        for
          built <- load
          repo  <- work("histos-wf-pins")
          files <- filesOf(built, finished)
          _     <- commit(repo, files)
          custom = Workflow.file(repo, "custom.yml")
          _       <- write(custom, "uses: actions/checkout@v4\n")
          faulted <- check(repo, built).exit
          _       <- update(repo, built)
          still   <- read(custom)
          again   <- check(repo, built).exit
        yield assertTrue(
          failureOf(faulted).contains(CiError.Pins(pinReport)),
          failureOf(again).contains(CiError.Pins(pinReport)),
          still == "uses: actions/checkout@v4\n",
        )
    ,
    test("a file at .github is missing, and update cannot write through it"):
      ZIO.scoped:
        for
          built <- load
          repo  <- work("histos-wf-blocked")
          blocked = repo.resolve(".github")
          _       <- write(blocked, "blocked\n")
          absent  <- present(repo).exit
          checked <- check(repo, built).exit
          wrote   <- update(repo, built).exit
          still   <- read(blocked)
        yield assertTrue(
          failureOf(absent).contains(CiError.Missing(Workflow.path(repo))),
          failureOf(checked).contains(CiError.Missing(Workflow.path(repo))),
          failureOf(wrote).contains(CiError.Io(IoFailure(Workflow.path(repo), IoFault.Write))),
          still == "blocked\n",
        )
    ,
    test("an unreadable ci.yml is still present, and check fails to read it"):
      ZIO.scoped:
        for
          built <- load
          repo  <- work("histos-wf-read")
          path = Workflow.path(repo)
          _      <- write(path, "name: ci\n")
          _      <- deny(path)
          there  <- present(repo)
          failed <- check(repo, built).exit
        yield assertTrue(
          there == (),
          failureOf(failed).contains(CiError.Io(IoFailure(path, IoFault.Read))),
        )
    ,
    test("a non-empty stale histos directory fails update as a delete fault"):
      ZIO.scoped:
        for
          built <- load
          repo  <- work("histos-wf-delete")
          files <- filesOf(built, finished)
          _     <- commit(repo, files)
          orphan = Workflow.file(repo, "histos-gone.yml")
          child  = orphan.resolve("child")
          _      <- makeDir(orphan)
          _      <- write(child, "x\n")
          failed <- update(repo, built).exit
          kept   <- read(child)
        yield assertTrue(
          failureOf(failed).contains(CiError.Io(IoFailure(orphan, IoFault.Delete))),
          kept == "x\n",
        ),
  )

  private def load: ZIO[Any, Fault, ProjectGraph] =
    ZIO.fromEither(graph)

  private def body(built: ProjectGraph): ZIO[Any, Fault, String] =
    ZIO.fromEither(Workflow.render(built))

  private def filesOf(built: ProjectGraph, sona: Publishing): ZIO[Any, Fault, List[RenderedWorkflow]] =
    ZIO.fromEither(Workflow.renderAll(built, sona))

  private def work(name: String): ZIO[Scope, Fault, Path] =
    Workspace.work(name)

  private def present(repo: Path): ZIO[Any, Fault, Unit] =
    Workflow.present(repo)

  private def check(repo: Path, built: ProjectGraph): ZIO[Any, Fault, Path] =
    Workflow.check(repo, built, finished)

  private def update(repo: Path, built: ProjectGraph): ZIO[Any, Fault, Path] =
    Workflow.update(repo, built, finished)

  private def write(path: Path, text: String): ZIO[Any, Fault, Unit] =
    Workspace.writeString(path, text)

  private def read(path: Path): ZIO[Any, Fault, String] =
    Workspace.readString(path)

  private def readMaybe(path: Path): ZIO[Any, Fault, Option[String]] =
    Workspace.readIfPresent(path)

  private def makeDir(path: Path): ZIO[Any, Fault, Path] =
    Workspace.createDirectories(path)

  private def remove(path: Path): ZIO[Any, Fault, Unit] =
    Workspace.delete(path)

  private def deny(path: Path): ZIO[Any, Fault, Unit] =
    ZIO
      .attemptBlocking:
        Files.setPosixFilePermissions(path, PosixFilePermissions.fromString("---------"))
        ()
      .mapError(_ => IoFailure(path, IoFault.Stat))

  private def commit(repo: Path, files: List[RenderedWorkflow]): ZIO[Any, Fault, Unit] =
    ZIO.foreachDiscard(files)(item => write(Workflow.file(repo, item.name), item.body))

  private def renderedBody(files: List[RenderedWorkflow], name: String): ZIO[Any, Fault, String] =
    files.find(_.name == name) match
      case Some(file) => ZIO.succeed(file.body)
      case None       => ZIO.fail(CiError.Drift(s".github/workflows/$name", "the file is missing"))

  private def entries(dir: Path): ZIO[Any, Fault, List[String]] =
    ZIO
      .attemptBlocking:
        if Files.isDirectory(dir) then
          val stream = Files.list(dir)
          val found  =
            try stream.iterator.asScala.toList
            finally stream.close()
          found.map(path => Option(path.getFileName).map(_.toString).getOrElse(""))
        else Nil
      .mapError(_ => IoFailure(dir, IoFault.Walk))

  private def retitle(body: String): String =
    val prefix = "name: ci\n"
    if body.startsWith(prefix) then "name: CI\n" + body.drop(prefix.length) else body

  private def failureOf[A](exit: Exit[Fault, A]): Option[Fault] =
    exit match
      case Exit.Success(_)     => None
      case Exit.Failure(cause) => cause.failureOption
end WorkflowFileLawSpec
